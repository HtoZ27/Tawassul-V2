
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { BASH_READ_ONLY } from "../permissions.ts";
import { ALL_AGENTS } from "../core/agent-data.ts";
import {
  EXACT_FAILURE_BLOCK_AFTER,
  SAME_TOOL_FAILURE_HALT_AFTER,
  NO_PROGRESS_BLOCK_AFTER,
} from "../hooks/guards/tool-loop-guard.ts";
import { readJsoncFile } from "../utils/opencode-config.ts";

const PLUGIN_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const FACTS_PATH = resolve(PLUGIN_ROOT, "FACTS.md");

export function buildFacts(): Record<string, string | number> {
  const jsoncPath = resolve(PLUGIN_ROOT, "../../../opencode.jsonc");
  const jsonPath = resolve(PLUGIN_ROOT, "../../../opencode.json");
  const cfgPath = existsSync(jsoncPath) ? jsoncPath : jsonPath;
  const config = readJsoncFile(cfgPath) as unknown as {
    agent: Record<string, { description?: string }>;
  };
  const agents = Object.keys(config.agent ?? {});
  const capsAgents = Object.values(config.agent ?? {}).filter((a) =>
    (a.description ?? "").includes("\nCapabilities: "),
  ).length;
  const values = Object.values(BASH_READ_ONLY);
  return {
    agentsTotal: agents.length,
    agentsWithCapabilityManifest: capsAgents,
    baseRoleTemplates: ALL_AGENTS.length,
    bashReadOnlyAllowPatterns: values.filter((v) => v === "allow").length,
    bashReadOnlyDenyPatterns: values.filter((v) => v === "deny").length,
    bashReadOnlyTotal: values.length,
    loopExactFailureBlockAfter: EXACT_FAILURE_BLOCK_AFTER,
    loopSameToolHaltAfter: SAME_TOOL_FAILURE_HALT_AFTER,
    loopNoProgressBlockAfter: NO_PROGRESS_BLOCK_AFTER,
  };
}

export function renderFacts(facts: Record<string, string | number>): string {
  const lines = [
    "# FACTS",
    "",
    "<!-- Generated by scripts/facts.ts — DO NOT EDIT BY HAND.",
    "     Regenerate after intentional changes: bun scripts/facts.ts write -->",
    "",
  ];
  for (const key of Object.keys(facts).sort()) {
    lines.push(`${key} = ${facts[key]}`);
  }
  lines.push("");
  return lines.join("\n");
}

export function parseFacts(content: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of content.split("\n")) {
    const m = line.match(/^([A-Za-z][A-Za-z0-9]+) = (.+)$/);
    if (m) out[m[1]!] = m[2]!;
  }
  return out;
}


if (process.argv[1] && process.argv[1].endsWith("facts.ts")) {
  if (process.argv[2] === "write") {
    const { writeFileSync } = await import("node:fs");
    writeFileSync(FACTS_PATH, renderFacts(buildFacts()), "utf-8");
    process.stdout.write(`[facts] wrote ${FACTS_PATH}\n`);
  } else {
    process.stdout.write(`${renderFacts(buildFacts())}\n`);
  }
}
