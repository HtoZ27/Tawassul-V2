import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = dirname(dirname(fileURLToPath(import.meta.url)));
const NOTICES_PATH = join(REPO, "THIRD-PARTY-NOTICES.md");

type Manifest = {
  name?: string;
  version?: string;
  license?: string;
  dependencies?: Record<string, string>;
  devDependencies?: Record<string, string>;
};

type LockEntry = { version?: string; dev?: boolean; license?: string };
type Lock = { packages?: Record<string, LockEntry> };
type PackageJson = { version?: string; license?: string };

const COPYLEFT = /(^|[^A-Za-z])(A?GPL|LGPL|MPL|SSPL|CPAL|EUPL)([^A-Za-z]|$)/;

const manifest = JSON.parse(readFileSync(join(REPO, "package.json"), "utf8")) as Manifest;
const lock = JSON.parse(readFileSync(join(REPO, "package-lock.json"), "utf8")) as Lock;

const direct = new Set([
  ...Object.keys(manifest.dependencies ?? {}),
  ...Object.keys(manifest.devDependencies ?? {}),
]);

type Row = { name: string; version: string; license: string; scope: string };
const rows: Row[] = [];
const problems: string[] = [];

function packageJsonFor(key: string): PackageJson | undefined {
  const file = join(REPO, key, "package.json");
  if (!existsSync(file)) return undefined;
  try {
    return JSON.parse(readFileSync(file, "utf8")) as PackageJson;
  } catch {
    return undefined;
  }
}

for (const [key, entry] of Object.entries(lock.packages ?? {})) {
  if (!key.startsWith("node_modules/")) continue;
  const segments = key.split("node_modules/").filter(Boolean);
  const name = segments[segments.length - 1];
  if (!name || name.startsWith(".")) continue;
  const installed = packageJsonFor(key);
  const version = entry.version ?? installed?.version ?? "";
  const license = installed?.license ?? entry.license ?? "";
  if (!version) {
    problems.push(`${name} has no version`);
    continue;
  }
  if (!license) {
    problems.push(`${name}@${version} has no licence field`);
    continue;
  }
  if (COPYLEFT.test(license)) {
    problems.push(`${name}@${version} carries a copyleft licence (${license})`);
  }
  rows.push({
    name,
    version,
    license,
    scope: direct.has(name) ? "direct" : entry.dev === false ? "transitive" : "development",
  });
}

rows.sort((a, b) => (a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name)));

if (problems.length > 0) {
  console.error("notices: refusing to write an incomplete inventory");
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}

const licenceCounts = new Map<string, number>();
for (const row of rows) licenceCounts.set(row.license, (licenceCounts.get(row.license) ?? 0) + 1);
const licences = [...licenceCounts.entries()].sort((a, b) => (b[1] === a[1] ? a[0].localeCompare(b[0]) : b[1] - a[1]));

const lines: string[] = [];
lines.push("# Third-party notices");
lines.push("");
lines.push("<!-- Generated by scripts/gen-third-party-notices.ts — DO NOT EDIT BY HAND.");
lines.push("     Regenerate after a dependency change: bun scripts/gen-third-party-notices.ts -->");
lines.push("");
lines.push(
  "Tawassul is distributed under the Apache License 2.0 (`LICENSE`). This page is the complete",
  "inventory of the installed tree at the release lockfile: every package, its installed",
  "version, its licence, and whether it is a direct dependency. `NOTICE.md` lists the",
  "components that ship inside the bundle or as wasm grammars.",
);
lines.push("");
lines.push(`Inventory: ${rows.length} packages, ${licences.length} licence expressions.`);
lines.push("");
lines.push("## Licence summary");
lines.push("");
lines.push("| Licence | Packages |");
lines.push("| --- | --- |");
for (const [licence, count] of licences) lines.push(`| \`${licence}\` | ${count} |`);
lines.push("");
lines.push("No copyleft licence (GPL, LGPL, AGPL, MPL, SSPL, CPAL, or EUPL) is present.");
lines.push("");
lines.push("## Inventory");
lines.push("");
lines.push("| Package | Version | Licence | Scope |");
lines.push("| --- | --- | --- | --- |");
for (const row of rows) lines.push(`| \`${row.name}\` | ${row.version} | \`${row.license}\` | ${row.scope} |`);
lines.push("");
lines.push("## How to verify");
lines.push("");
lines.push("```bash");
lines.push("npm run check:notices");
lines.push("```");
lines.push("");
lines.push("The fast gate fails when this file drifts from `package-lock.json`, when a package");
lines.push("has no licence, or when a copyleft licence appears.");
lines.push("");
const rendered = `${lines.join("\n")}\n`;

const args = process.argv.slice(2);

if (args.includes("--check")) {
  if (!existsSync(NOTICES_PATH)) {
    console.error("notices: THIRD-PARTY-NOTICES.md is missing; run npm run notices");
    process.exit(1);
  }
  const current = readFileSync(NOTICES_PATH, "utf8");
  if (current !== rendered) {
    console.error("notices: THIRD-PARTY-NOTICES.md is stale; run npm run notices");
    process.exit(1);
  }
  console.log(`notices: OK (${rows.length} packages, ${licences.length} licence expressions, no copyleft)`);
} else if (args.includes("--stdout")) {
  process.stdout.write(rendered);
} else {
  writeFileSync(NOTICES_PATH, rendered);
  console.log(`notices: wrote ${NOTICES_PATH} (${rows.length} packages, no copyleft)`);
}
